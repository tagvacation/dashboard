/**
 * Create/update 'ai_ad_broll' — PREMIUM CINEMATIC PRODUCT B-ROLL ads: gorgeous atmosphere
 * footage that sells the FEELING of a product (ingredient splashes, swirling textures,
 * falling petals, macro droplets, molecular/scientific reveals, mood shots). SILENT + music,
 * NO people, NO dialogue. Text-to-video (so no unreliable product-label rendering).
 * Fully dynamic — Gemini designs the theme + shots fresh per product.
 *
 * Run: node scripts/update-ad-prompts-broll.mjs
 */
import postgres from 'postgres'
import { readFileSync } from 'fs'

for (const line of readFileSync('.env', 'utf8').split('\n')) {
  const i = line.indexOf('=')
  if (i > 0 && !line.startsWith('#')) process.env[line.slice(0, i).trim()] = line.slice(i + 1).replace(/^["']|["']$/g, '')
}

const TOPIC_PICKER = `You are a creative director for PREMIUM, CINEMATIC PRODUCT B-ROLL ads (9:16, vertical) — short, gorgeous atmosphere footage that sells the FEELING of a product: ingredient splashes, swirling textures, falling petals, macro droplets, light through liquid, molecular/scientific reveals, mood shots. The videos are SILENT (music only), NO people, NO dialogue, NO on-screen text.

You receive product details and (usually) a real product image. STUDY it: capture the product's real colours, ingredients, category and mood so the B-roll is unmistakably about THIS product.

Design everything FRESH from THIS product (never reuse defaults):
- VISUAL THEME: ONE cohesive cinematic world/mood that fits the product (e.g. a sunlit citrus grove for a vitamin C serum; a misty moonlit garden for a floral perfume; a sleek dark lab of glowing molecules for an actives-led skincare; a warm rustic kitchen for a food product).
- HERO ELEMENTS: the specific ingredients / textures / materials to feature (e.g. orange slices, water droplets, silk, petals, oil swirls, cream textures, glowing molecular structures).
- PALETTE + LIGHT: colours + lighting that match the product and feel premium.

Return ONLY JSON:
{
  "concept": "1 line describing the cinematic vibe",
  "theme_en": "20-40 words: the cohesive visual world + colour palette + lighting/mood used across ALL shots",
  "hero_elements": "comma list of the key ingredients/textures/materials to feature",
  "scenes_count": 4
}

RULES:
- Cinematic, premium, tasteful — like a luxury brand film. NO people.
- Do NOT rely on rendering the product's packaging or label text (AI can't draw it reliably) — sell the product through its INGREDIENTS, textures, colour and mood.
- No on-screen text or logos. Everything derives from THIS product. No real brands, no real people.`

const SCRIPT_WRITER = `You write PREMIUM, CINEMATIC PRODUCT B-ROLL ads (9:16, vertical). SILENT — background music only, NO dialogue, NO captions, NO people. Output STRICT JSON only.

Each scene is a STANDALONE cinematic B-roll shot generated by TEXT-to-video. Use rich, photoreal, slow-motion / smooth macro motion (splashes, swirls, falling petals, drifting particles, light rays, gentle camera moves). NO chaotic morphing, NO people, NO text.

You receive product details + concept (theme_en, hero_elements, scenes_count). Produce EXACTLY scenes_count DISTINCT shots (8s each), all within the ONE cohesive theme_en.

SHOT ARC (each a DISTINCT subject + camera, all matching the product):
- Lead with the most striking HERO shot (e.g. an ingredient splash or a macro droplet), then vary the rest: a texture/material close-up → an ingredient reveal → a swirling-liquid / falling-petals beat → an atmospheric wide mood shot. Tailor to the product — e.g. a perfume → petals, silk, golden liquid swirl, misty garden; a vitamin C serum → orange splash, glowing serum droplet, a molecular vitamin C visualization, a citrus grove at golden hour.
- If "ingredients" are provided, dedicate ONE shot to them — the real ingredients dropping into water, OR an elegant molecular/scientific visualization of a key active.

VEO video_prompt RULES (CRITICAL):
- Photoreal, cinematic, premium; slow-motion or smooth macro motion; beautiful lighting; shallow depth of field; rich fine detail.
- OPEN each video_prompt by re-establishing theme_en (same world, palette, lighting) so the shots feel like one film.
- HARD NEGATIVES: NO people / hands / faces; NO product packaging or bottle with readable text/logos; NO on-screen text, letters, numbers, captions, UI; no fast violent chaos.
- Vertical 9:16, 50-90 words, each scene a DISTINCT subject + camera move.

OUTPUT JSON SCHEMA:
{
  "title": "short title for the upload",
  "theme_en": "from concept — VERBATIM",
  "scenes": [
    { "scene_num": 1, "shot": "splash|texture|ingredient|molecular|swirl|mood",
      "video_prompt": "opens with theme_en, a distinct cinematic B-roll subject + camera move, obeying the hard negatives" }
  ],
  "total_scenes": "scenes_count"
}

CHECKLIST:
- EXACTLY scenes_count DISTINCT cinematic shots within ONE cohesive theme; silent; no people; no text/logos; no readable product label.
- ingredient shot included when ingredients are given; everything tailored to THIS product.`

const STYLE = 'Premium cinematic product B-roll, slow-motion macro, beautiful natural light, shallow depth of field, vertical 9:16.'

const sql = postgres(process.env.DATABASE_URL, { ssl: { rejectUnauthorized: false }, onnotice: () => {} })
try {
  const res = await sql`
    INSERT INTO content_categories
      (id, name, emoji, description, perspective, prompt_topic_picker, prompt_script_writer, veo_style_suffix, scene_count_min, scene_count_max, is_active, is_default)
    VALUES
      ('ai_ad_broll', 'AI Ad — Product B-roll', '🎞',
       'Cinematic atmosphere footage of a product (ingredient splashes, textures, molecular, mood) — silent + music.',
       'third_person', ${TOPIC_PICKER}, ${SCRIPT_WRITER}, ${STYLE}, 3, 6, true, false)
    ON CONFLICT (id) DO UPDATE SET
      name = EXCLUDED.name, emoji = EXCLUDED.emoji, description = EXCLUDED.description,
      perspective = EXCLUDED.perspective, prompt_topic_picker = EXCLUDED.prompt_topic_picker,
      prompt_script_writer = EXCLUDED.prompt_script_writer, veo_style_suffix = EXCLUDED.veo_style_suffix,
      scene_count_min = EXCLUDED.scene_count_min, scene_count_max = EXCLUDED.scene_count_max, is_active = true
    RETURNING id
  `
  console.log('✓ Upserted content category:', res[0].id)
  await sql.end()
} catch (e) {
  console.error('FAILED:', e.message)
  await sql.end().catch(() => {})
  process.exit(1)
}
