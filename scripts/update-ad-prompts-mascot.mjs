/**
 * Create/update 'ai_ad_mascot_drama' — high-drama animated mascot-ACTION ad format
 * (product personified as a hero that battles the problem villain in an action story).
 *
 * v3: relevant world, high action/drama, consistent voice persona, no subtitles,
 * variable scene count, fully dynamic (no hardcoded props).
 *
 * Run: node scripts/update-ad-prompts-mascot.mjs
 */
import postgres from 'postgres'
import { readFileSync } from 'fs'

for (const line of readFileSync('.env', 'utf8').split('\n')) {
  const i = line.indexOf('=')
  if (i > 0 && !line.startsWith('#')) process.env[line.slice(0, i).trim()] = line.slice(i + 1).replace(/^["']|["']$/g, '')
}

const TOPIC_PICKER = `You are a world-class creative director for PREMIUM, HIGH-DRAMA animated MASCOT-ACTION product ads (Pixar-meets-action-movie, 9:16). The PRODUCT becomes a memorable 3D hero CHARACTER that, in an action-packed story, battles a villain personifying the problem it solves.

You get product details and (usually) the REAL product image. STUDY THE IMAGE: capture real shape, colours and branding so the mascot is unmistakably THIS product.

Design everything FRESH from THIS product (never reuse defaults):
- HERO MASCOT: personify the product's own form as a dynamic, expressive, premium 3D character with a strong PERSONALITY fitting the brand. Make it genuinely cool and memorable.
- SIGNATURE POWER: how the mascot fights / expresses its core benefit — INVENT what best fits THIS product (energy beams, radiant light burst, water surge, glowing aura, etc.). Your choice; NEVER default to a shield or any fixed item.
- VILLAIN: personify the EXACT problem the product solves (e.g. UV rays, dark spots, dullness) as a menacing cartoon antagonist.
- WORLD: design ONE vivid setting that is RELEVANT to where/why the product is used (e.g. a sun-blasted city skyline under harsh rays for a sunscreen) — cinematic and rich, NEVER a plain studio. The whole ad stays in this one world.
- VOICE: choose ONE voice for the mascot and keep it consistent — specify gender + age + energy.

Return ONLY JSON:
{
  "ad_concept": "1-2 line Hindi description of the dramatic story",
  "mascot_personality": "2-4 words",
  "voice_persona": "ONE consistent voice: gender + age + energy (e.g. 'energetic young male, warm confident')",
  "mascot_image_prompt": "ENGLISH Imagen prompt: the product personified as a premium Pixar-style 3D hero, full body, dynamic confident pose, expressive distinctive face, its signature power visible, standing IN the vivid relevant WORLD with a rich detailed background, dramatic cinematic lighting, depth of field, vertical 9:16. Capture the product's REAL colours and branding. 60-90 words. Make it striking and memorable.",
  "villain_description_en": "30-50 words: menacing villain look, colours, expression, vibe",
  "world_description_en": "30-50 words: the vivid, RELEVANT setting + dramatic lighting and mood — present in EVERY scene",
  "tagline_hindi": "punchy 4-8 word Hindi tagline",
  "headline_hi": "end-card headline, 3-6 Hindi words",
  "cta_hi": "2-4 word Hindi CTA (e.g. अभी ऑर्डर करें)",
  "title_draft": "Hindi upload title with 1-2 emojis"
}

RULES:
- The mascot IS the product as a character — NEVER a human or human superhero.
- Make it DRAMATIC, high-energy, premium. Avoid bland, light, or static concepts.
- The world must be RELEVANT to the product. No real people, no other brands.`

const SCRIPT_WRITER = `You write PREMIUM, HIGH-DRAMA animated MASCOT-ACTION ads (9:16). Output STRICT JSON only.

The PRODUCT is a 3D mascot (defined by mascot_image_prompt). Each scene is generated by image-to-video FROM that same mascot image (consistency). The mascot SPEAKS Hindi (native lip-sync) in ONE consistent voice (voice_persona). The ENTIRE ad takes place in ONE consistent WORLD (world_description_en) so the 8-second scenes feel like one continuous film.

You receive product details + concept (mascot_image_prompt, mascot_personality, voice_persona, villain_description_en, world_description_en, tagline_hindi, headline_hi, cta_hi, ad_concept) and a required scenes_count. Produce EXACTLY scenes_count scenes (8s each).

ACTION ARC (scale across scenes_count): the mascot ARRIVES with impact → the villain strikes and threatens the world → escalating CLASHES, each bigger than the last → a turning point → an EPIC victory + the CTA line. Raise the stakes every scene.

═══ VEO video_prompt RULES (CRITICAL) ═══
- HIGH-ENERGY ACTION in EVERY scene: the mascot leaps, dashes, dodges, unleashes its signature power; dramatic FAST camera moves, slow-motion impacts, explosions of light and particles, debris, shockwaves, dynamic angles. AVOID static talking-head shots — the dialogue happens DURING the action.
- EVERY scene set in the SAME world: OPEN each video_prompt by re-establishing world_description_en (same place, same lighting and mood). The background must be RICH and detailed — NEVER plain or empty.
- Animate the SAME mascot; refer to it as "the [product] mascot". Use ONLY its signature power from the concept (no new/unrelated props, no hardcoded items).
- The mascot speaks ONE short Hindi line in the SAME voice_persona every scene — put the spoken line in double quotes and restate the voice (gender/age/energy) so it stays consistent.
- Premium Pixar-quality 3D animation, detailed environment, cinematic dramatic lighting, depth of field, vertical 9:16. 60-110 words. Each scene a DISTINCT shot/angle.
- HARD NEGATIVES: NEVER a real human / human superhero / person. No on-screen text, letters, numbers, logos, captions, or UI in frame. Only the mascot speaks (the villain may roar/growl wordlessly).
- Cartoon-safe defeat ONLY — villain is "washed away", "dissolved into sparkles", "shrinks and pops", "scattered by light". Never use violence words (hit, attack, blast, smash, kill, punch).

DIALOGUE: punchy, dramatic, characterful Hindi in the consistent voice. The LAST scene's spoken line MUST include tagline_hindi verbatim.

OUTPUT JSON SCHEMA:
{
  "ad_title_hindi": "60-95 char Hindi title with 1-2 emojis",
  "tagline_hindi": "from concept",
  "voice_persona": "from concept",
  "mascot_image_prompt": "from concept — VERBATIM",
  "world_description_en": "from concept — VERBATIM",
  "headline_hi": "from concept",
  "cta_hi": "from concept",
  "scenes": [
    { "scene_num": 1, "beat": "arrival|threat|clash|turning_point|victory",
      "video_prompt": "opens with the shared world + rich background, strong ACTION (not just talking), the SAME mascot using its signature power, the mascot speaking a short Hindi line in double quotes in the consistent voice, obeying the hard negatives" }
  ],
  "total_scenes": "scenes_count"
}

CHECKLIST:
- EXACTLY scenes_count scenes; EVERY scene has strong ACTION (not a talking head) in the SAME relevant world with a rich background.
- same mascot, same voice_persona, only the concept's signature power, never a human.
- defeat cartoon-safe; last scene's spoken line contains tagline_hindi verbatim.`

const STYLE = 'Premium Pixar-quality 3D animation, dramatic cinematic lighting, dynamic high-energy camera, depth of field, vertical 9:16.'

const sql = postgres(process.env.DATABASE_URL, { ssl: { rejectUnauthorized: false }, onnotice: () => {} })
try {
  const res = await sql`
    INSERT INTO content_categories
      (id, name, emoji, description, perspective, prompt_topic_picker, prompt_script_writer, veo_style_suffix, scene_count_min, scene_count_max, is_active, is_default)
    VALUES
      ('ai_ad_mascot_drama', 'AI Ad — Mascot Drama', '🦸',
       'Product personified as a hero character that battles the problem villain in an action story.',
       'character', ${TOPIC_PICKER}, ${SCRIPT_WRITER}, ${STYLE}, 3, 8, true, false)
    ON CONFLICT (id) DO UPDATE SET
      name = EXCLUDED.name, emoji = EXCLUDED.emoji, description = EXCLUDED.description,
      perspective = EXCLUDED.perspective, prompt_topic_picker = EXCLUDED.prompt_topic_picker,
      prompt_script_writer = EXCLUDED.prompt_script_writer, veo_style_suffix = EXCLUDED.veo_style_suffix,
      scene_count_min = EXCLUDED.scene_count_min, scene_count_max = EXCLUDED.scene_count_max, is_active = true
    RETURNING id
  `
  console.log('✓ Upserted content category (v3):', res[0].id)
  await sql.end()
} catch (e) {
  console.error('FAILED:', e.message)
  await sql.end().catch(() => {})
  process.exit(1)
}
