/**
 * Create/update 'ai_ad_mascot_drama' — high-drama animated mascot-ACTION ad format
 * (product personified as a hero that battles the problem villain in an action story).
 *
 * v3: relevant world, high action/drama, consistent voice persona, no subtitles,
 * variable scene count, fully dynamic (no hardcoded props).
 *
 * Run: node scripts/update-ad-prompts-mascot.mjs
 */
import postgres from 'postgres'
import { readFileSync } from 'fs'

for (const line of readFileSync('.env', 'utf8').split('\n')) {
  const i = line.indexOf('=')
  if (i > 0 && !line.startsWith('#')) process.env[line.slice(0, i).trim()] = line.slice(i + 1).replace(/^["']|["']$/g, '')
}

const TOPIC_PICKER = `You are a world-class creative director for PREMIUM, HIGH-DRAMA animated MASCOT-ACTION product ads (Pixar-meets-action-movie, 9:16). The PRODUCT becomes a memorable 3D hero CHARACTER that, in an action-packed story, battles a villain personifying the problem it solves.

You get product details and (usually) the REAL product image. STUDY THE IMAGE: capture real shape, colours and branding so the mascot is unmistakably THIS product.

Design everything FRESH from THIS product (never reuse defaults):
- HERO MASCOT: personify the product's own form as a dynamic, expressive, premium 3D character with a strong PERSONALITY fitting the brand. Make it genuinely cool and memorable.
- SIGNATURE POWER: how the mascot fights / expresses its core benefit — INVENT what best fits THIS product (energy beams, radiant light burst, water surge, glowing aura, etc.). Your choice; NEVER default to a shield or any fixed item.
- VILLAIN: personify the EXACT problem the product solves (e.g. UV rays, dark spots, dullness) as a menacing cartoon antagonist.
- WORLD: design ONE vivid setting that is RELEVANT to where/why the product is used (e.g. a sun-blasted city skyline under harsh rays for a sunscreen) — cinematic and rich, NEVER a plain studio. The whole ad stays in this one world.
- VOICE: choose ONE voice for the mascot and keep it consistent — specify gender + age + energy.

Return ONLY JSON:
{
  "ad_concept": "1-2 line Hindi description of the dramatic story",
  "mascot_personality": "2-4 words",
  "voice_persona": "ONE consistent voice: gender + age + energy (e.g. 'energetic young male, warm confident')",
  "mascot_image_prompt": "ENGLISH Imagen prompt: the product personified as a premium Pixar-style 3D hero, full body, dynamic confident pose, expressive distinctive face, its signature power visible, standing IN the vivid relevant WORLD with a rich detailed background, dramatic cinematic lighting, depth of field, vertical 9:16. Capture the product's REAL colours and branding. 60-90 words. Make it striking and memorable.",
  "villain_description_en": "30-50 words: menacing villain look, colours, expression, vibe",
  "world_description_en": "30-50 words: the vivid, RELEVANT setting + dramatic lighting and mood — present in EVERY scene",
  "tagline_hinglish": "punchy 4-8 word HINGLISH spoken catchphrase (natural Hindi+English mix, the way Indians actually talk)",
  "headline_en": "end-card headline in ENGLISH, 3-6 words",
  "cta_en": "end-card CTA button in ENGLISH, 2-3 words (e.g. Shop Now, Buy Now)",
  "title_draft": "Hindi/Hinglish upload title with 1-2 emojis"
}

RULES:
- The mascot IS the product as a character — NEVER a human or human superhero.
- Make it DRAMATIC, high-energy, premium. Avoid bland, light, or static concepts.
- The world must be RELEVANT to the product. No real people, no other brands.`

const SCRIPT_WRITER = `You write PREMIUM animated MASCOT ads (9:16). Output STRICT JSON only.

The PRODUCT is a 3D mascot — a cute OBJECT-WITH-A-FACE (defined by mascot_image_prompt), NEVER a human. Each scene is generated by image-to-video FROM that same mascot image (consistency). The mascot SPEAKS Hindi (native lip-sync) in ONE consistent voice (voice_persona). The ENTIRE ad takes place in ONE consistent WORLD (world_description_en) so the 8-second scenes feel like one continuous film.

You receive product details + a creative concept that includes "ad_archetype" and "structure" (the ordered beats for THIS ad), plus mascot_image_prompt, voice_persona, world_description_en, villain_description_en (may be EMPTY), tagline_hinglish, headline_en, cta_en, ad_concept, hook. Produce EXACTLY scenes_count scenes (8s each).

═══ FOLLOW THE ARCHETYPE — DO NOT FORCE A VILLAIN FIGHT ═══
Different ads use different archetypes; the story MUST match the given ad_archetype + structure:
- Map the concept's "structure" beats across the scenes IN ORDER (stretch/repeat proportionally if scenes_count > beats). Use those beat ids in each scene's "beat" field.
- SCENE 1 is always a punchy COLD-OPEN HOOK — dramatize the concept's "hook" to stop the scroll in the first 1-2 seconds.
- The LAST scene delivers the payoff + the spoken tagline and visually leads to the end card.
- VILLAIN/ANTAGONIST: include one ONLY if villain_description_en is non-empty (hero_vs_villain). Then render it EXACTLY as villain_description_en every time, and defeat it cartoon-safe. For ALL other archetypes there is NO villain — the engagement comes from the archetype itself (transformation, satisfying sensory beats, a journey, a relatable moment, hype, comparison, or rhythm).

═══ VEO video_prompt RULES (CRITICAL) ═══
- MATCH THE ENERGY to the archetype: high-energy dynamic action for hero_vs_villain / world_adventure / mini_musical; calm, premium, tactile macro shots for asmr_satisfying / transformation; warm + relatable for day_in_life; confident + direct (but with a live camera + world) for hype_testimonial / comparison_playful. Avoid a flat static talking-head.
- CAMERA: give EACH scene a DISTINCT camera move (push-in, low-angle, sweeping orbit, crane up, whip-pan, slow dolly, macro rack-focus) — never repeat the same framing twice in a row.
- EVERY scene set in the SAME world: OPEN each video_prompt by re-establishing world_description_en (same place, same lighting and mood). Background RICH and detailed — NEVER plain or empty.
- Animate the SAME mascot; refer to it as "the [product] mascot". It STAYS the product object with a face — it NEVER grows a human body/arms/legs, never becomes a person/superhero/robot. Only gentle, on-character motion + expression.
- The mascot speaks ONE short HINGLISH line in the SAME voice_persona every scene — put the spoken line in double quotes and restate the voice (gender/age/energy) so it stays consistent.
- Premium Pixar-quality 3D animation, detailed environment, cinematic lighting, depth of field, vertical 9:16. 60-110 words. Each scene a DISTINCT shot/angle.
- HARD NEGATIVES: NEVER a real human / human superhero / person. No on-screen text, letters, numbers, logos, captions, or UI in frame. Only the mascot speaks.
- Keep it cartoon-safe and positive — never violence words (hit, attack, blast, smash, kill, punch). Any "problem" is washed away / dissolved into sparkles / shrinks and pops / scattered by light.

DIALOGUE: punchy, characterful HINGLISH (natural Hindi+English code-mix, the way Indians really talk in ads — e.g. "Tan ko bolo bye-bye, glow ko bolo hello!"). Same voice every scene. The LAST scene's spoken line MUST include tagline_hinglish verbatim.

PRONUNCIATION (CRITICAL for correct spoken audio): write the HINDI words in DEVANAGARI script and keep ENGLISH words in Latin — e.g. "Hairfall की छुट्टी!", "मज़बूत बाल, हमेशा". Do NOT romanize Hindi words (romanized "chhutti"/"majboot" get mis-pronounced as "chutti"/"majbot"). The line still reads as natural Hinglish, just with Hindi in Devanagari.

INGREDIENTS: if the input includes "ingredients", ONE scene (best at the product/proof beat) MUST have the mascot proudly NAME its key ingredients/actives and what they do — e.g. "मुझ में है [ingredient] और [ingredient], जो [problem] से लड़ें!" (keep ingredient names as given).

OUTPUT JSON SCHEMA:
{
  "ad_title_hindi": "60-95 char Hindi/Hinglish title with 1-2 emojis",
  "ad_archetype": "from concept — VERBATIM",
  "tagline_hinglish": "from concept",
  "voice_persona": "from concept",
  "mascot_image_prompt": "from concept — VERBATIM",
  "world_description_en": "from concept — VERBATIM",
  "headline_en": "from concept (ENGLISH end-card headline)",
  "cta_en": "from concept (ENGLISH end-card button)",
  "scenes": [
    { "scene_num": 1, "beat": "the beat id from the concept's structure for this scene",
      "action": "one-line ENGLISH summary of the scene's visual action (for storyboard review)",
      "dialogue": "the mascot's HINGLISH spoken line for this scene",
      "video_prompt": "opens with the shared world + rich background, energy matched to the archetype, the SAME object-with-a-face mascot (never a human), the mascot speaking the Hinglish dialogue line in double quotes in the consistent voice, obeying the hard negatives" }
  ],
  "total_scenes": "scenes_count"
}

CHECKLIST:
- EXACTLY scenes_count scenes that FOLLOW the concept's ad_archetype + structure (NOT a forced villain fight).
- a villain appears ONLY if villain_description_en is non-empty.
- same mascot (object with a face, never a human), same world, same voice_persona; cartoon-safe; last scene's dialogue contains tagline_hinglish verbatim.`

const STYLE = 'Premium Pixar-quality 3D animation, dramatic cinematic lighting, dynamic high-energy camera, depth of field, vertical 9:16.'

const sql = postgres(process.env.DATABASE_URL, { ssl: { rejectUnauthorized: false }, onnotice: () => {} })
try {
  const res = await sql`
    INSERT INTO content_categories
      (id, name, emoji, description, perspective, prompt_topic_picker, prompt_script_writer, veo_style_suffix, scene_count_min, scene_count_max, is_active, is_default)
    VALUES
      ('ai_ad_mascot_drama', 'AI Ad — Mascot Drama', '🦸',
       'Product personified as a hero character that battles the problem villain in an action story.',
       'character', ${TOPIC_PICKER}, ${SCRIPT_WRITER}, ${STYLE}, 3, 8, true, false)
    ON CONFLICT (id) DO UPDATE SET
      name = EXCLUDED.name, emoji = EXCLUDED.emoji, description = EXCLUDED.description,
      perspective = EXCLUDED.perspective, prompt_topic_picker = EXCLUDED.prompt_topic_picker,
      prompt_script_writer = EXCLUDED.prompt_script_writer, veo_style_suffix = EXCLUDED.veo_style_suffix,
      scene_count_min = EXCLUDED.scene_count_min, scene_count_max = EXCLUDED.scene_count_max, is_active = true
    RETURNING id
  `
  console.log('✓ Upserted content category (v3):', res[0].id)
  await sql.end()
} catch (e) {
  console.error('FAILED:', e.message)
  await sql.end().catch(() => {})
  process.exit(1)
}
